-- Module 1: core lead tables.
--
-- leads            one row per submission, contact data in typed columns
-- lead_insurances  one row per selected insurance type, answers as jsonb
-- consents         proof of what the user agreed to (GDPR)
--
-- Security: RLS is enabled on every table with no policies, and all
-- privileges are revoked from anon and authenticated. Only the server,
-- using the secret key (service_role), can read or write.

-- ---------------------------------------------------------------------------
-- Shared trigger function: keep updated_at current
-- ---------------------------------------------------------------------------

create function public.set_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

revoke all on function public.set_updated_at() from public, anon, authenticated;

-- ---------------------------------------------------------------------------
-- leads
-- ---------------------------------------------------------------------------

create table public.leads (
  id uuid primary key default gen_random_uuid(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),

  -- Idempotency key generated by the client per submission, so a double
  -- submit cannot create two leads.
  submission_id uuid not null unique,

  first_name text not null check (char_length(first_name) between 1 and 100),
  last_name text not null check (char_length(last_name) between 1 and 100),
  -- Stored lowercased so lookups (e.g. GDPR access and erasure requests)
  -- match regardless of how the user typed it.
  email text not null check (
    char_length(email) between 3 and 254
    and position('@' in email) > 1
    and email = lower(email)
  ),
  phone text not null check (char_length(phone) between 8 and 20),

  -- Address fields are nullable here; which ones are required is enforced
  -- by the zod schema for the selected insurance types.
  street_address text check (char_length(street_address) between 1 and 200),
  postal_code text check (postal_code ~ '^[0-9]{4}$'),
  city text check (char_length(city) between 1 and 100),
  -- Identifier from the address lookup (module 6), if the user picked one.
  address_id text check (char_length(address_id) between 1 and 100)
);

comment on table public.leads is
  'One row per form submission. Contains personal data: do not log, keep in the EU.';

create index leads_email_idx on public.leads (email);
create index leads_created_at_idx on public.leads (created_at);

create trigger leads_set_updated_at
  before update on public.leads
  for each row execute function public.set_updated_at();

-- ---------------------------------------------------------------------------
-- lead_insurances
-- ---------------------------------------------------------------------------

create table public.lead_insurances (
  id uuid primary key default gen_random_uuid(),
  created_at timestamptz not null default now(),
  lead_id uuid not null references public.leads (id) on delete cascade,
  insurance_type text not null check (
    insurance_type in ('car', 'home_contents', 'house')
  ),
  -- Answers for this insurance type, shaped by the form config and
  -- validated by the generated zod schema on the server.
  answers jsonb not null default '{}'::jsonb check (jsonb_typeof(answers) = 'object'),
  -- Version of the form config the answers were collected with.
  form_version text not null check (char_length(form_version) between 1 and 50),

  unique (lead_id, insurance_type)
);

comment on table public.lead_insurances is
  'One row per insurance type selected on a lead, with the form answers.';

-- ---------------------------------------------------------------------------
-- consents
-- ---------------------------------------------------------------------------

create table public.consents (
  id uuid primary key default gen_random_uuid(),
  lead_id uuid not null references public.leads (id) on delete cascade,
  consent_type text not null check (
    consent_type in ('partner_contact', 'marketing')
  ),
  granted boolean not null,
  -- Exact text shown to the user, so we can prove what they agreed to even
  -- after the wording changes.
  consent_text text not null check (char_length(consent_text) between 1 and 5000),
  consent_version text not null check (char_length(consent_version) between 1 and 50),
  recorded_at timestamptz not null default now(),

  unique (lead_id, consent_type)
);

comment on table public.consents is
  'Consent given or declined per lead, with the exact text shown.';

-- ---------------------------------------------------------------------------
-- Access: server only
-- ---------------------------------------------------------------------------

alter table public.leads enable row level security;
alter table public.lead_insurances enable row level security;
alter table public.consents enable row level security;

revoke all on table public.leads, public.lead_insurances, public.consents
  from anon, authenticated;

grant select, insert, update, delete
  on table public.leads, public.lead_insurances, public.consents
  to service_role;
